def resolve_host(hostname):
    """
    Resolve a hostname to an IPv4 address.

    Args:
        hostname (str):
            Hostname or IP address to resolve.

    Returns:
        str | None:
            Resolved IPv4 address if successful.
            None if DNS resolution fails.
    """

    try:
        return socket.gethostbyname(hostname)
    except socket.gaierror:
        return None


def send_tcp_syslog(server, port, message):
    """
    Send a single message to a remote syslog receiver using TCP.

    Args:
        server (str):
            Destination syslog hostname or IP address.

        port (int):
            Destination TCP port.

        message (str):
            Message payload to send.

    Returns:
        None
    """

    data = (message + "\n").encode("utf-8")

    with socket.create_connection(
        (server, port),
        timeout=10,
    ) as sock:
        sock.sendall(data)


def send_udp_syslog(server, port, message):
    """
    Send a single message to a remote syslog receiver using UDP.

    Args:
        server (str):
            Destination syslog hostname or IP address.

        port (int):
            Destination UDP port.

        message (str):
            Message payload to send.

    Returns:
        None
    """

    data = message.encode("utf-8")

    sock = socket.socket(
        socket.AF_INET,
        socket.SOCK_DGRAM,
    )

    try:
        sock.sendto(
            data,
            (server, port),
        )
    finally:
        sock.close()


def main():
    """
    Main Ansible module entry point.

    The module:
      1. Receives a list of inventory hosts.
      2. Resolves each hostname using DNS.
      3. Builds one JSON inventory event per host.
      4. Sends the event to the configured syslog receiver.
      5. Returns processing results to Ansible.
    """

    module = AnsibleModule(
        argument_spec=dict(
            hosts=dict(
                type="list",
                elements="str",
                required=True,
            ),
            syslog_server=dict(
                type="str",
                required=True,
            ),
            syslog_port=dict(
                type="int",
                default=514,
            ),
            protocol=dict(
                type="str",
                choices=[
                    "tcp",
                    "udp",
                ],
                default="tcp",
            ),
        ),
        supports_check_mode=True,
    )

    hosts = module.params["hosts"]
    server = module.params["syslog_server"]
    port = module.params["syslog_port"]
    protocol = module.params["protocol"]

    results = []

    timestamp = datetime.datetime.now(
        datetime.timezone.utc
    ).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )

    for hostname in hosts:

        ip = resolve_host(hostname)

        event = {
            "event_type": "host_inventory",
            "hostname": hostname,
            "ip": ip,
            "source": "ansible_aap",
            "status": "active" if ip else "dns_failed",
            "inventory_timestamp": timestamp,
        }

        message = json.dumps(
            event,
            separators=(",", ":"),
        )

        if not module.check_mode:

            if protocol == "tcp":
                send_tcp_syslog(
                    server,
                    port,
                    message,
                )

            else:
                send_udp_syslog(
                    server,
                    port,
                    message,
                )

        results.append(event)

    module.exit_json(
        changed=False,
        processed=len(hosts),
        results=results,
    )


if __name__ == "__main__":
    main()
